def run_negative_controls() -> list[dict]:
    def touch(root: Path) -> None:
        (root / "observer.py").write_text("# rewritten during inventory\n")

    def drop_additional(m: dict) -> None:
        m["assets"] = [a for a in m["assets"] if a["path"] != "factory_status.sh"]

    def tamper_hash(m: dict) -> None:
        m["assets"][0]["identity"]["sha256"] = "0" * 64

    def invent_retirement(m: dict) -> None:
        a = next(a for a in m["assets"] if a["path"] == "liveness.py")
        a["custody"]["class"] = "RETIRE_CANDIDATE"

    def widen_unknown(m: dict) -> None:
        a = next(a for a in m["assets"] if a["path"] == "factory_status.sh")
        a["custody"]["unknowns"][0]["blocks"].append("liveness.py")

    controls = [
        ("discovery_beyond_historical_eighteen", "fixed-list inventory omits a newly discovered asset",
         drop_additional, "verify", "completeness"),
        ("exact_identity", "recorded sha256 no longer matches the asset bytes", tamper_hash, "verify", "identity"),
        ("truthful_custody_class", "live protection relabelled with an invented retirement class",
         invent_retirement, "check", "custody_class"),
        ("unknown_locality", "UNKNOWN for one asset widened to block an unrelated asset",
         widen_unknown, "check", "unknown_locality"),
        ("zero_effect", "an asset is rewritten during the inventory pass", None, "check", "zero_effect"),
    ]
    records = []
    for control_id, fault, mutate, gate, expected in controls:
        with tempfile.TemporaryDirectory() as tmp:
            intact, root = _fixture_manifest(Path(tmp) / "intact")
            gate_fn = (lambda m: check_manifest(m) + verify_against_root(m, root)) if gate == "verify" else check_manifest
            intact_failures = gate_fn(intact)
            if mutate is None:
                faulted, _ = _fixture_manifest(Path(tmp) / "fault", during=touch)
                fault_failures = check_manifest(faulted)
            else:
                faulted = copy.deepcopy(intact)
                mutate(faulted)
                fault_failures = gate_fn(faulted)
            restored, root = _fixture_manifest(Path(tmp) / "restored")
            restored_failures = gate_fn(restored)
        detected = any(f.startswith(expected + ":") for f in fault_failures)
        records.append({
            "control": control_id, "fault": fault, "gate": gate, "expected_failure_check": expected,
            "applications": 1,
            "intact": {"passed": not intact_failures, "failures": intact_failures},
            "fault_result": {"detected": detected, "failures": fault_failures},
            "restored": {"passed": not restored_failures, "failures": restored_failures},
            "verdict": "PASS" if (not intact_failures and detected and not restored_failures) else "FAIL",
        })
    return records


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate")
    g.add_argument("--root", type=Path, default=DEFAULT_BOOTSTRAP)
    g.add_argument("--unit-dir", type=Path, default=DEFAULT_UNIT_DIR)
    g.add_argument("--revision", default="HEAD")
    g.add_argument("--output", type=Path)
    c = sub.add_parser("check")
    c.add_argument("manifest", type=Path)
    c.add_argument("--root", type=Path, help="also rediscover this live root and compare")
    n = sub.add_parser("controls")
    n.add_argument("--output", type=Path)
    args = parser.parse_args(argv)

    if args.cmd == "generate":
        manifest = generate(args.root, args.unit_dir, revision=args.revision)
        body = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
        if args.output:
            args.output.write_text(body)
        failures = check_manifest(manifest)
        print(json.dumps({"assets": len(manifest["assets"]), "summary": manifest["summary"],
                          "unchanged": manifest["side_effect_check"]["unchanged"], "failures": failures}, indent=2))
        return 1 if failures else 0
    if args.cmd == "check":
        manifest = json.loads(args.manifest.read_text())
        failures = check_manifest(manifest)
        if args.root:
            failures += verify_against_root(manifest, args.root)
        print(json.dumps({"result": "FAIL" if failures else "PASS", "failures": failures}, indent=2))
        return 1 if failures else 0
    records = run_negative_controls()
    body = json.dumps({"fixture": "FX-B0", "controls": records}, indent=2, sort_keys=True) + "\n"
    if args.output:
        args.output.write_text(body)
    print(body, end="")
    return 0 if all(r["verdict"] == "PASS" for r in records) else 1


