_READ_ONLY_GIT = {"grep", "ls-tree", "log", "rev-parse", "cat-file"}
# Read-only results keyed by argv; revisions are resolved to full SHAs before any keyed read.
_GIT_CACHE: dict[tuple, str] = {}


class Runner:
    """Records every subprocess; refuses anything but read-only git subcommands."""

    def __init__(self, repo: Path):
        self.repo = repo
        self.commands: list[list[str]] = []

    def git(self, *args: str) -> str:
        if not args or args[0] not in _READ_ONLY_GIT:
            raise PermissionError(f"refused non-read-only command: git {' '.join(args)}")
        argv = ["git", *args]
        self.commands.append(argv)
        key = (str(self.repo), tuple(argv))
        if key not in _GIT_CACHE or args[0] == "rev-parse":
            done = subprocess.run(argv, cwd=self.repo, capture_output=True, text=True)
            if not (done.returncode == 0 or (args[0] == "grep" and done.returncode == 1 and not done.stderr)):
                raise RuntimeError(f"{' '.join(argv)} failed ({done.returncode}): {done.stderr.strip()}")
            _GIT_CACHE[key] = done.stdout
        return _GIT_CACHE[key]


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _git_blob(data: bytes) -> str:
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def discover(root: Path) -> list[str]:
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in EXCLUDED_DIRS)
        for name in filenames:
            found.append((Path(dirpath) / name).relative_to(root).as_posix())
    return sorted(found)


def snapshot(*dirs: Path) -> dict:
    """Full state of each directory, caches included: type, mode, size, mtime_ns, sha256."""
    state = {}
    for base in dirs:
        if not base.exists():
            state[str(base)] = "ABSENT"
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames.sort()
            for name in sorted(dirnames + filenames):
                p = Path(dirpath) / name
                st = p.lstat()
                entry = {"mode": st.st_mode, "mtime_ns": st.st_mtime_ns}
                if p.is_symlink():
                    entry["link"] = os.readlink(p)
                elif p.is_file():
                    entry |= {"size": st.st_size, "sha256": _sha256(p.read_bytes())}
                state[str(p)] = entry
    return state


def _digest(value) -> str:
    return "sha256:" + _sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode())


def _units(unit_dir: Path) -> tuple[dict[str, str], set[str]]:
    units, enabled = {}, set()
    if not unit_dir.is_dir():
        return units, enabled
    for p in sorted(unit_dir.iterdir()):
        if p.is_file() and not p.is_symlink():
            units[p.name] = p.read_text(errors="replace")
        elif p.is_dir() and p.name.endswith(".wants"):
            enabled.update(child.name for child in p.iterdir())
    return units, enabled


def _processes(proc_root: Path) -> list[dict] | str:
    if not proc_root.is_dir():
        return "UNKNOWN: process table not readable"
    rows = []
    for p in proc_root.iterdir():
        if not p.name.isdigit() or int(p.name) == os.getpid():
            continue
        try:
            argv = [a for a in (p / "cmdline").read_bytes().decode(errors="replace").split("\0") if a]
        except OSError:
            continue
        rows.append({"pid": int(p.name), "argv": argv})
    return sorted(rows, key=lambda r: r["pid"])


def _references(rel: str, text_by_asset: dict[str, str]) -> list[str]:
    name = Path(rel).name
    stem = Path(rel).stem
    pattern = re.compile(rf"(^|\W)(import\s+{re.escape(stem)}\b|from\s+{re.escape(stem)}\s+import\b)|"
                         rf"(?<![\w-]){re.escape(name)}", re.M)
    return sorted(other for other, text in text_by_asset.items()
                  if other != rel and pattern.search(text))


def _classify(rel: str, observed: dict, head_paths: set[str], policy: dict) -> dict:
    entry = policy.get(rel)
    if entry is None:
        return {"class": UNKNOWN, "group": "unclassified", "evidence": [],
                "basis": "Discovered asset with no custody policy entry.",
                "unknowns": [{"question": "No custody evidence or decision exists for this newly discovered asset.",
                              "blocks": [rel]}],
                "migration_deletion_retirement_authorized": False}
    if entry["class"] not in TAXONOMY:
        raise ValueError(f"{rel}: policy class {entry['class']!r} is outside the custody taxonomy")
    custody = {k: entry[k] for k in ("class", "group", "basis", "evidence")}
    custody["unknowns"] = [{"question": q, "blocks": [rel]} for q in entry.get("questions", [])]
    live = observed["service_units"] or observed["processes"]
    if entry["class"] == HISTORICAL and live:
        custody["class"] = UNKNOWN
        custody["unknowns"].append({"question": "Policy says historical, but a live consumer (service unit or "
                                    "process) was observed; the conflict must be resolved.", "blocks": [rel]})
    counterpart = entry.get("counterpart")
    if counterpart:
        custody["replacement_ref"] = counterpart
        if entry["class"] == CANDIDATE and counterpart not in head_paths:
            custody["class"] = UNKNOWN
            custody["unknowns"].append({"question": f"Named successor {counterpart} is absent at the pinned "
                                        "repository revision.", "blocks": [rel]})
    if custody["class"] == UNKNOWN and not custody["unknowns"]:
        custody["unknowns"].append({"question": "Custody undecided.", "blocks": [rel]})
    custody["migration_deletion_retirement_authorized"] = False
    return custody


def generate(root: Path = DEFAULT_BOOTSTRAP, unit_dir: Path = DEFAULT_UNIT_DIR, proc_root: Path = Path("/proc"),
             repo: Path = ROOT, revision: str = "HEAD", policy: dict | None = None,
             clock=lambda: dt.datetime.now(dt.timezone.utc), during=None) -> dict:
    policy = POLICY if policy is None else policy
    runner = Runner(repo)
    before = snapshot(root, unit_dir)
    started = clock()

    rev = runner.git("rev-parse", revision).strip()
    head_blobs: dict[str, list[str]] = {}
    for line in runner.git("ls-tree", "-r", rev).splitlines():
        meta, path = line.split("\t", 1)
        head_blobs.setdefault(meta.split()[2], []).append(path)
    head_paths = {p for paths in head_blobs.values() for p in paths}

    paths = discover(root)
    data = {rel: (root / rel).read_bytes() for rel in paths}
    text = {rel: raw.decode(errors="replace") for rel, raw in data.items()}
    units, enabled = _units(unit_dir)
    procs = _processes(proc_root)
    root_s = str(root)

    if during is not None:
        during(root)

    blobs = {rel: _git_blob(raw) for rel, raw in data.items()}
    history: dict[str, list[dict]] = {}
    commit = None
    for line in runner.git("log", "--raw", "--no-abbrev", "--no-renames", "--format=C %H %s", rev).splitlines():
        if line.startswith("C "):
            sha, _, subject = line[2:].partition(" ")
            commit = {"commit": sha, "subject": subject}
        elif line.startswith(":") and commit:
            for blob in line.split("\t", 1)[0].split()[2:4]:
                touched = history.setdefault(blob, [])
                if not touched or touched[-1] is not commit:
                    touched.append(commit)

    names = sorted({Path(rel).name for rel in paths} | {f"alienintent-bootstrap/{rel}" for rel in paths})
    mentions: dict[str, set[str]] = {}
    grep_args = ["grep", "-o", "-F"] + [a for n in names for a in ("-e", n)] + [rev, "--"]
    for line in runner.git(*grep_args).splitlines():
        _, path, match = line.split(":", 2)
        mentions.setdefault(match, set()).add(path)

    assets = []
    for rel in paths:
        raw = data[rel]
        abs_path = f"{root_s}/{rel}"
        unit_refs = []
        for unit, body in units.items():
            expanded = body.replace("%h", str(HOME)).replace("~/", f"{HOME}/")
            lines = [ln.strip() for ln in expanded.splitlines() if abs_path in ln]
            if lines:
                unit_refs.append({"unit": unit, "enabled_via_wants_link": unit in enabled, "lines": lines})
        proc_refs = procs if isinstance(procs, str) else [p for p in procs if abs_path in p["argv"]]
        qualified = f"alienintent-bootstrap/{rel}"
        repo_refs = sorted(mentions.get(qualified, set()))
        basename_mentions = mentions.get(Path(rel).name, set()) | set(repo_refs)
        blob = blobs[rel]
        bootstrap_refs = _references(rel, text)
        observed = {"service_units": unit_refs, "processes": proc_refs if isinstance(proc_refs, list) else []}
        custody = _classify(rel, observed, head_paths, policy)
        if custody.get("replacement_ref"):
            ref = custody["replacement_ref"]
            custody["replacement_ref_status"] = ("ABSENT" if ref not in head_paths else
                                                 "IDENTICAL" if ref in head_blobs.get(blob, []) else "DIFFERS")
        st = (root / rel).stat()
        assets.append({
            "path": rel,
            "absolute_path": abs_path,
            "in_historical_eighteen": rel in HISTORICAL_EIGHTEEN,
            "identity": {"sha256": _sha256(raw), "git_blob": blob, "size": len(raw),
                         "mode": oct(st.st_mode & 0o7777),
                         "mtime_utc": dt.datetime.fromtimestamp(st.st_mtime, dt.timezone.utc).isoformat()},
            "consumers": {
                "bootstrap_assets": bootstrap_refs,
                "service_units": unit_refs,
                "processes": proc_refs,
                "repository_qualified_references": {
                    "code": [p for p in repo_refs if not p.startswith("docs/")],
                    "docs": [p for p in repo_refs if p.startswith("docs/")]},
                "repository_basename_mentions_unattributed": len(basename_mentions),
            },
            "provenance": {
                "repository_paths_with_identical_bytes": sorted(head_blobs.get(blob, [])),
                "repository_commits_touching_blob": history.get(blob, []),
                "bootstrap_tests": [r for r in bootstrap_refs if Path(r).name.startswith("test_")],
            },
            "custody": custody,
        })

    after = snapshot(root, unit_dir)
    discovered = set(paths)
    summary = {cls: sum(1 for a in assets if a["custody"]["class"] == cls) for cls in TAXONOMY}
    return {
        "schema_version": "1",
        "artifact_type": "bootstrap_custody_manifest",
        "work_unit": "WO-220501",
        "issue": "AlienLogicLab/alienintent#116",
        "proof_fixture": "FX-B0",
        "status": "READ_ONLY_INVENTORY; NO MIGRATION, DELETION, SERVICE CHANGE, CUTOVER OR RETIREMENT AUTHORITY",
        "provenance": {
            "generated_at": started.isoformat(),
            "generator": "tools/evidence/bootstrap_custody_manifest.py",
            "generator_sha256": _sha256(Path(__file__).read_bytes()),
            "repository_revision": rev,
            "bootstrap_root": root_s,
            "unit_dir": str(unit_dir),
            "process_table": str(proc_root),
            "observation_limits": [
                "Process and unit observations are a point-in-time readback on the producing host.",
                "Unit activation is inferred only from *.wants links; systemctl is never invoked.",
                "Repository basename mentions may collide with unrelated files, so they are counted, not attributed.",
                "mtime is recorded for context only; identity is sha256 and git blob.",
            ],
        },
        "taxonomy": TAXONOMY,
        "discovery": {
            "excluded_cache_dirs": list(EXCLUDED_DIRS),
            "discovered_count": len(paths),
            "historical_eighteen_present": sorted(discovered & set(HISTORICAL_EIGHTEEN)),
            "historical_eighteen_missing": sorted(set(HISTORICAL_EIGHTEEN) - discovered),
            "additional_to_historical_eighteen": sorted(discovered - set(HISTORICAL_EIGHTEEN)),
            "policy_entries_not_discovered": sorted(set(policy) - discovered),
        },
        "assets": assets,
        "summary": summary,
        "side_effect_check": {
            "scope": [root_s, str(unit_dir)],
            "before_digest": _digest(before),
            "after_digest": _digest(after),
            "unchanged": before == after,
            "changed_paths": sorted(k for k in set(before) | set(after) if before.get(k) != after.get(k)),
            "commands_executed": runner.commands,
        },
    }


def check_manifest(manifest: dict) -> list[str]:
    failures = []
    if manifest.get("artifact_type") != "bootstrap_custody_manifest":
        failures.append("artifact_type: not a bootstrap_custody_manifest")
    assets = manifest.get("assets") or []
    if not assets:
        failures.append("assets: empty inventory")
    paths = [a.get("path") for a in assets]
    if len(set(paths)) != len(paths):
        failures.append("assets: duplicate paths")
    for a in assets:
        rel = a.get("path", "<unnamed>")
        ident = a.get("identity", {})
        if not re.fullmatch(r"[0-9a-f]{64}", str(ident.get("sha256", ""))):
            failures.append(f"identity: {rel} lacks an exact sha256")
        if not re.fullmatch(r"[0-9a-f]{40}", str(ident.get("git_blob", ""))):
            failures.append(f"identity: {rel} lacks a git blob id")
        custody = a.get("custody", {})
        cls = custody.get("class")
        if cls not in TAXONOMY:
            failures.append(f"custody_class: {rel} has {cls!r}, not one of {tuple(TAXONOMY)}")
            continue
        if custody.get("migration_deletion_retirement_authorized") is not False:
            failures.append(f"no_invented_authority: {rel} claims migration/deletion/retirement authority")
        for unknown in custody.get("unknowns", []):
            if unknown.get("blocks") != [rel]:
                failures.append(f"unknown_locality: {rel} unknown blocks {unknown.get('blocks')}, not only itself")
        if cls == UNKNOWN and not custody.get("unknowns"):
            failures.append(f"unknown_explicit: {rel} is UNKNOWN without a stated unknown")
        if cls != UNKNOWN and not (custody.get("basis") and custody.get("evidence")):
            failures.append(f"classification_evidence: {rel} is {cls} without basis and evidence")
        consumers = a.get("consumers", {})
        if cls == HISTORICAL and (consumers.get("service_units") or consumers.get("processes")):
            failures.append(f"truthful_class: {rel} is historical despite an observed live consumer")
        if cls == CANDIDATE and not custody.get("replacement_ref"):
            failures.append(f"truthful_class: {rel} is a replacement candidate without a named successor")
    disc = manifest.get("discovery", {})
    present = set(paths)
    for name in HISTORICAL_EIGHTEEN:
        if name not in present and name not in disc.get("historical_eighteen_missing", []):
            failures.append(f"discovery: historical module {name} neither inventoried nor reported missing")
    if sorted(present - set(HISTORICAL_EIGHTEEN)) != disc.get("additional_to_historical_eighteen"):
        failures.append("discovery: additional-asset list disagrees with the inventory")
    if disc.get("discovered_count") != len(assets):
        failures.append("discovery: discovered_count disagrees with the inventory")
    summary = {cls: sum(1 for a in assets if a.get("custody", {}).get("class") == cls) for cls in TAXONOMY}
    if manifest.get("summary") != summary:
        failures.append("summary: class counts disagree with the inventory")
    effects = manifest.get("side_effect_check", {})
    if effects.get("unchanged") is not True or effects.get("before_digest") != effects.get("after_digest"):
        failures.append(f"zero_effect: inventory pass changed {effects.get('changed_paths')}")
    for argv in effects.get("commands_executed", []):
        if argv[:1] != ["git"] or len(argv) < 2 or argv[1] not in _READ_ONLY_GIT:
            failures.append(f"zero_effect: non-read-only command recorded {argv}")
    return failures


def verify_against_root(manifest: dict, root: Path) -> list[str]:
    """Rediscover root and compare path set and content identity with the manifest."""
    failures = []
    recorded = {a["path"]: a["identity"]["sha256"] for a in manifest.get("assets", [])}
    current = {rel: _sha256((root / rel).read_bytes()) for rel in discover(root)}
    for rel in sorted(set(current) - set(recorded)):
        failures.append(f"completeness: discovered asset {rel} is missing from the manifest")
    for rel in sorted(set(recorded) - set(current)):
        failures.append(f"completeness: manifest asset {rel} no longer exists")
    for rel in sorted(set(recorded) & set(current)):
        if recorded[rel] != current[rel]:
            failures.append(f"identity: {rel} sha256 differs from current bytes")
    return failures


